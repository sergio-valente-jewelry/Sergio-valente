function setLanguage(lang){
  const t=translations[lang]||translations.fr;
  document.documentElement.lang=lang;
  document.querySelectorAll("[data-i18n]").forEach(el=>{
    const key=el.dataset.i18n;
    if(t[key]) el.textContent=t[key];
  });
  document.querySelectorAll(".languages button").forEach(b=>{
    b.classList.toggle("active",b.dataset.lang===lang);
  });
  localStorage.setItem("sv-language",lang);
}
document.querySelectorAll(".languages button").forEach(b=>{
  b.addEventListener("click",()=>setLanguage(b.dataset.lang));
});
setLanguage(localStorage.getItem("sv-language")||"fr");

// Filtres professionnels des collections
(function(){
  const filters = document.querySelectorAll('.collection-filter');
  const cards = document.querySelectorAll('.collection-card');
  if(!filters.length || !cards.length) return;

  filters.forEach(filter => {
    filter.addEventListener('click', () => {
      const value = filter.dataset.filter;
      filters.forEach(btn => btn.classList.toggle('active', btn === filter));
      cards.forEach(card => {
        const categories = (card.dataset.category || '').split(' ');
        const visible = value === 'all' || categories.includes(value);
        card.hidden = !visible;
      });
    });
  });
})();


// Galerie : agrandissement + informations
(function(){
  const cards = document.querySelectorAll('.collection-card');
  const lightbox = document.getElementById('collectionLightbox');
  const image = document.getElementById('lightboxImage');
  const title = document.getElementById('lightboxTitle');
  const description = document.getElementById('lightboxDescription');
  if(!cards.length || !lightbox) return;

  let lastCard = null;

  function currentText(key){
    const source = document.querySelector('[data-i18n="' + key + '"]');
    return source ? source.textContent : key;
  }

  function openCard(card){
    lastCard = card;
    image.src = card.dataset.image;
    image.alt = currentText(card.dataset.titleKey);
    title.textContent = currentText(card.dataset.titleKey);
    description.textContent = currentText(card.dataset.descKey);
    lightbox.hidden = false;
    document.body.classList.add('lightbox-open');
    const closeButton = lightbox.querySelector('.lightbox-close');
    if(closeButton) closeButton.focus();
  }

  function closeLightbox(){
    lightbox.hidden = true;
    document.body.classList.remove('lightbox-open');
    image.src = '';
    if(lastCard) lastCard.focus();
  }

  cards.forEach(card=>{
    card.addEventListener('click',()=>openCard(card));
    card.addEventListener('keydown',(event)=>{
      if(event.key === 'Enter' || event.key === ' '){
        event.preventDefault();
        openCard(card);
      }
    });
  });

  lightbox.addEventListener('click',(event)=>{
    if(event.target.matches('[data-lightbox-close]')) closeLightbox();
  });

  document.addEventListener('keydown',(event)=>{
    if(!lightbox.hidden && event.key === 'Escape') closeLightbox();
  });
})();


